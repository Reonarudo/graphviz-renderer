import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);

test('vendored files match SHA256SUMS', () => {
  const sums = readFileSync('vendor/viz/SHA256SUMS', 'utf8').trim().split('\n');
  assert.deepEqual(sums.map((line) => line.split(/\s+/)[1]).sort(), ['provenance.json', 'viz.cjs']);
  for (const line of sums) {
    const [expected, name] = line.split(/\s+/) as [string, string];
    const actual = createHash('sha256').update(readFileSync(`vendor/viz/${name}`)).digest('hex');
    assert.equal(actual, expected, name);
  }
});

test('the provenance is viz-js built from the unmodified Graphviz 16.0.0 release', () => {
  const provenance = JSON.parse(readFileSync('vendor/viz/provenance.json', 'utf8'));
  const sources = provenance.predicate.buildDefinition.resolvedDependencies as { uri: string; digest: { sha256?: string } }[];
  const graphviz = sources.find((source) => source.uri.endsWith('/graphviz-16.0.0.tar.gz'));
  assert.equal(graphviz?.digest.sha256, '36a1de1aaf5a2023b14f95170a5f8f0b12522d1c305b517fc261966597050749');
});

test('the regeneration script pins the vendored @viz-js/viz release', () => {
  const script = readFileSync('scripts/vendor-viz.sh', 'utf8');
  assert.match(script, /^VERSION=3\.30\.0$/m);
  assert.match(script, /^INTEGRITY=sha512-2zmcP55QY44uQfZ\+GvgNHmGd8S6KUD\+2eMur9AbYybSzrOd\/m8nMUg0ZircJNiJRKGgVBKAE8kh0hAwpUFUFQQ==$/m);
});

test('vendored viz is Graphviz 16.0.0 and renders svg_inline synchronously', async () => {
  const viz = await require('../vendor/viz/viz.cjs').instance();
  assert.equal(viz.graphvizVersion, '16.0.0');
  const result = viz.render('digraph { a -> b }', { format: 'svg_inline' });
  assert.equal(result.status, 'success');
  // svg_inline has no XML prolog or stylesheet processing instruction, but it does lead with
  // generator comments and its root <svg> carries no xmlns — the sanitizer has to expect both.
  assert.match(result.output, /^<!-- Generated by graphviz version 16\.0\.0/);
  assert.match(result.output, /<svg width=/);
  assert.doesNotMatch(result.output, /<svg[^>]*xmlns=/);
  assert.doesNotMatch(result.output, /<\?xml/);
});
